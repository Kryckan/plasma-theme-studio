from plasma_theme_studio.apply import desktop
from plasma_theme_studio.apply.runner import Result
from plasma_theme_studio.generators import CSS_MARKER, JSON_MARKER, MARKER, XML_MARKER, made_here
from plasma_theme_studio.generators import base as base_module


def test_every_marker_is_recognised(tmp_path):
    for index, marker in enumerate((MARKER, XML_MARKER, JSON_MARKER, CSS_MARKER)):
        path = tmp_path / f"file{index}"
        path.write_text(f"{marker}\nbody\n")
        assert made_here(path)


def test_css_marker_is_a_block_comment_and_foreign_css_is_not_ours(tmp_path):
    assert CSS_MARKER == "/* Generated by Plasma Theme Studio. */"
    assert CSS_MARKER in base_module.MARKERS
    foreign = tmp_path / "gtk.css"
    foreign.write_text("/* My own tweaks. */\nwindow { }\n")
    assert not made_here(foreign)
    assert not made_here(tmp_path / "missing.css")


def test_pause_is_replaced_by_the_fixture(pauses):
    desktop.pause(1.5)
    assert pauses == [1.5]


def test_notify_change_uses_dbus_send(runner):
    runner.handlers["dbus-send"] = lambda argv: Result(0)
    assert desktop.notify_change(runner, desktop.CHANGE_STYLE).returncode == 0
    assert runner.calls[-1] == [
        "dbus-send",
        "--session",
        "--type=signal",
        "/KGlobalSettings",
        "org.kde.KGlobalSettings.notifyChange",
        "int32:2",
        "int32:0",
    ]


def test_notify_change_passes_the_argument(runner):
    runner.handlers["dbus-send"] = lambda argv: Result(0)
    desktop.notify_change(runner, desktop.CHANGE_CURSOR, 3)
    assert runner.calls[-1][-2:] == ["int32:5", "int32:3"]


def test_notify_change_falls_back_to_busctl(runner):
    runner.missing.add("dbus-send")
    runner.handlers["busctl"] = lambda argv: Result(0)
    assert desktop.notify_change(runner, desktop.CHANGE_PALETTE).returncode == 0
    assert runner.calls[-1] == [
        "busctl",
        "--user",
        "emit",
        "/KGlobalSettings",
        "org.kde.KGlobalSettings",
        "notifyChange",
        "ii",
        "0",
        "0",
    ]


def test_notify_change_without_any_tool_fails_quietly(runner):
    runner.missing.update({"dbus-send", "busctl"})
    result = desktop.notify_change(runner, desktop.CHANGE_FONT)
    assert result.returncode != 0
    assert runner.calls == []


def test_notify_change_reports_a_failing_tool(runner):
    runner.handlers["dbus-send"] = lambda argv: Result(1, "", "no bus")
    assert desktop.notify_change(runner, desktop.CHANGE_ICONS).returncode == 1


def test_a_file_is_captured_and_restored(tmp_path):
    path = tmp_path / "a/settings.ini"
    path.parent.mkdir()
    path.write_text("[Settings]\nx=1\n")
    saved = desktop.capture_file(path)
    assert saved == "[Settings]\nx=1\n"
    path.write_text("changed")
    desktop.restore_file(path, saved)
    assert path.read_text() == saved


def test_a_file_that_did_not_exist_is_removed_again(tmp_path):
    path = tmp_path / "new/file.css"
    saved = desktop.capture_file(path)
    assert saved == desktop.ABSENT == "absent"
    path.parent.mkdir()
    path.write_text("x")
    desktop.restore_file(path, saved)
    assert not path.exists()
    desktop.restore_file(path, saved)  # nothing to do, nothing raised


def test_a_missing_file_is_written_back_with_its_folder(tmp_path):
    path = tmp_path / "gone/dir/file"
    desktop.restore_file(path, "text\n")
    assert path.read_text() == "text\n"


def test_a_file_that_is_a_link_stays_a_link(tmp_path):
    target = tmp_path / "dotfiles/gtk.css"
    target.parent.mkdir()
    target.write_text("old")
    link = tmp_path / "gtk.css"
    link.symlink_to(target)
    saved = desktop.capture_file(link)
    target.write_text("new")
    desktop.restore_file(link, saved)
    assert link.is_symlink() and target.read_text() == "old"
    desktop.restore_file(link, desktop.ABSENT)
    assert link.is_symlink() and target.read_text() == ""


def test_a_file_that_is_not_text_cannot_be_captured(tmp_path):
    path = tmp_path / "blob"
    path.write_bytes(b"\xff\xfe\x00")
    try:
        desktop.capture_file(path)
    except OSError:
        return
    raise AssertionError("expected OSError")


def test_a_file_with_windows_line_endings_comes_back_byte_for_byte(tmp_path):
    path = tmp_path / "a.conf"
    path.write_bytes(b"[General]\r\ntheme=x\r\n")
    saved = desktop.capture_file(path)
    path.write_bytes(b"other\n")
    desktop.restore_file(path, saved)
    assert path.read_bytes() == b"[General]\r\ntheme=x\r\n"
